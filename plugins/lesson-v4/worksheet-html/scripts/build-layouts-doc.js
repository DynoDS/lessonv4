#!/usr/bin/env node
"use strict";

// The page shapes the worksheet-designer chooses from, generated from the code.
//
//   npm run layouts
//
// This replaces a hand-written document that described three named compositions
// with region budgets, and a hand-maintained table of which content fitted
// which. There are thirty-two shapes and forty-seven variants now, tried in two
// orientations, and a table of that kept by hand would be wrong within a week.
//
// More to the point, it does not need keeping. The engine can be ASKED - that
// is what `npm run suggest` is - so the document's job is to say what the
// shapes ARE and in what millimetres, and to send the designer to the engine
// for the question only the engine can answer.
//
// Millimetres, not proportions. The designer's other document states every
// helper's smallest usable size in millimetres, and a shape described as
// "30 / 70, stacked" cannot be compared against "needs 84mm tall" without
// arithmetic nobody should be doing in their head.

const fs = require("node:fs");
const path = require("node:path");

const { LAYOUTS, VARIANTS, zonesOf } = require("../src/layouts");
const { printableArea, DEFAULT_MARGIN_MM } = require("../src/page");
const { GUTTER_MM, zoneContentMm } = require("../src/render");

// A zone's real size on paper, so it can be read against a helper's minimum.
function sizesFor(layout, orientation) {
  // zoneContentMm is the renderer's own answer, and it is used rather than
  // repeated on purpose. Its comment says why: the sum used to live in three
  // places, one of them forgot the gutter, and a recording table was approved
  // against 90mm and then handed 84 - so its last column came out too narrow
  // for a child to write in, on a page that looked finished. A document that
  // states sizes a helper is then refused at would do the same thing again.
  const area = printableArea(orientation);

  return zonesOf(layout).map((z) => {
    const { wMm, hMm } = zoneContentMm(z, area);
    return { id: z.id, w: Math.round(wMm), h: Math.round(hMm) };
  });
}

function table(layout) {
  const portrait = sizesFor(layout, "portrait");
  const landscape = sizesFor(layout, "landscape");

  const rows = portrait.map((z, i) => {
    const l = landscape[i];
    return `| \`${z.id}\` | ${z.w} x ${z.h} | ${l.w} x ${l.h} |`;
  });

  return [
    "| zone | portrait (mm) | landscape (mm) |",
    "|---|---|---|",
    ...rows,
  ].join("\n");
}

function entry(layout) {
  return [
    `#### \`${layout.id}\``,
    "",
    layout.name + (layout.variant ? "  *(a ratio variant)*" : ""),
    "",
    table(layout),
    "",
  ].join("\n");
}

function main() {
  const all = [...LAYOUTS, ...VARIANTS];

  const out = [
    "<!-- GENERATED by `npm run layouts` in worksheet-html. Do not edit by hand. -->",
    "",
    "# Page shapes",
    "",
    `${LAYOUTS.length} shapes and ${VARIANTS.length} variants, with what each`,
    "zone measures on real paper.",
    "",
    "A variant is the same shape at different proportions, or the same zones in",
    "different places: mirrored top to bottom, mirrored left to right, or turned on its",
    "side. They are generated rather than written out, so the arrangement you need",
    "exists whether or not anyone thought to draw it.",
    "",
    "**Content is never reordered to find a fit.** Zones fill in reading order, because",
    "a fluency set often gets harder as it goes and a later question can depend on an",
    "earlier one. So if the biggest item is second, the shape whose biggest zone is",
    "second is what you want, and that is what the variants are for.",
    "",
    "## What a layout is",
    "",
    "**Geometry, and nothing else.** A layout says how the page is divided, not what",
    "goes in it. One shape serves a geography lesson and a maths lesson without being",
    "rebuilt, exactly as a slide template does.",
    "",
    "A zone knows it is 180mm by 70mm. It does not know what goes in it. There is no",
    "stimulus zone and no reasoning zone: naming a zone after a teaching job ties every",
    "layout to one kind of lesson, and that is the mistake this engine was rebuilt to",
    "end. Choose the shape that holds the content, then decide what goes where.",
    "",
    "## Choosing one",
    "",
    "**Normally, don't.** A sheet written with `\"layout\": \"auto\"` and its zones",
    "as an array in reading order has its shape chosen by the engine: every layout",
    "here is tried at both orientations and the one closest to comfortably full",
    "wins. Comfortably full, not fullest, because heights are estimates and a",
    "browser draws the real page a shade taller or shorter - a shape with room to",
    "spare absorbs the difference, while a shape filled to the brim clips and is",
    "refused.",
    "",
    "**Choose by hand when the teaching wants a particular arrangement** - one big",
    "shared grid rather than six small ones, flanks pointing inward at a middle, a",
    "deliberately short sheet. Then ask the engine for the ranked options rather",
    "than reading this list end to end: write the zone contents to a JSON file (a",
    "bare array, or `{ \"items\": [...] }`), then:",
    "",
    "```",
    "node worksheet-html/scripts/suggest.js <content.json> <yearGroup>",
    "```",
    "",
    "**One entry per ZONE, in reading order - not one per helper.** Each entry is",
    "exactly what that zone will hold, so an entry is usually a `stack` of several",
    "helpers and a two-column sheet is two entries. Asking about a zone's helpers",
    "one at a time asks about one-zone layouts instead, and the answer will not",
    "match what the build then measures.",
    "",
    "It returns every shape that holds the content, best first, where best means",
    "most comfortably full. It is doing arithmetic against each helper's stated",
    "minimum, which is the part worth handing over; which of the shapes it offers",
    "suits the TEACHING is the part it cannot answer, and that is the designer's",
    "to choose.",
    "",
    "The sizes below are what the suggestion is measured against, so they are here to",
    "check a judgement rather than to be searched.",
    "",
    "## What the numbers mean",
    "",
    `Every sheet is A4 with a ${DEFAULT_MARGIN_MM}mm margin, and the gutter between`,
    `zones (${GUTTER_MM}mm) is already taken off. So these are the millimetres a helper`,
    "actually gets, and they can be read straight against the **smallest usable** size",
    "in the helper catalogue.",
    "",
    "A helper asking for more than its zone offers is refused with a reason. It is",
    "never squashed, and nothing is trimmed to make it fit.",
    "",
    "### A width is a promise; a height is a plan",
    "",
    "**Widths are printed as stated.** A zone in a 30 / 70 side-by-side split really",
    "is a third of the page wide, and a helper that needs more is refused there. So",
    "choosing between `side-30-70` and `side-50-50` is a real choice with a real",
    "consequence, and it is worth making.",
    "",
    "**Heights are not.** Every zone is finally sized to what it holds: the engine",
    "measures the content, adds a tolerance, lets a helper whose content IS space",
    "claim what is spare, and leaves the rest at the foot of the page. The parts in a",
    "top-to-bottom split only order the search; nothing forces a zone to the height",
    "they name. That is deliberate, and it is the right way round - a stacked zone",
    "held to 30% would either cut the content that did not fit or print a hole under",
    "content that finished early, and both are worse than a page that follows what is",
    "on it.",
    "",
    "The consequence to know about: **the seven `stacked-` ratios cannot differ from",
    "each other, or from `halves-stacked`.** Given the same content they render the",
    "same bytes. They are kept so that a saved sheet naming one still builds, and",
    "because the fit search costs nothing to try them, but choosing between them is",
    "not a decision - it is the same page under seven names. If a stacked page is",
    "coming out wrong, the thing to change is what is IN the zones or their order,",
    "never which stacked ratio is named.",
    "",
    "So in the tables below, read a portrait height under a top-to-bottom split as",
    "the planning figure the fit search used, not as the millimetres that will print.",
    "The widths are exact.",
    "",
    "## What this document no longer decides",
    "",
    "The hand-written version carried three things besides the shapes. None is lost,",
    "and none of them belongs in a generated file:",
    "",
    "- **How the three sheets differ.** \"Changing only names, numbers, quantities or",
    "  question count is not differentiation\" is a teaching principle, not a page",
    "  shape. It lives in the worksheet-designer's own instructions.",
    "- **Typeface, colour and rules.** The engine owns these now and states them in one",
    "  place. The old text named Arial and a 14pt title, which the pipeline had already",
    "  overruled: the typeface is locked across slides, worksheets and the working wall",
    "  together. Nothing here should be choosing a font.",
    "- **How full a page must be.** The old rule was 78% to 94% of printable height.",
    "  The engine measures fill but the threshold is deliberately UNSET, because it",
    "  should come from real lessons rather than a number picked in advance. Until it",
    "  is set: a strip left at the foot is fine, a teacher trims it. Half a page",
    "  missing is not. Do not pad a sheet to fill it.",
    "",
    "---",
    "",
  ];

  for (const layout of all) out.push(entry(layout));

  const file = path.join(__dirname, "..", "..", "references", "worksheet-compositions.md");
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, out.join("\n"));
  console.log(`Wrote ${file}`);
  console.log(`${LAYOUTS.length} shapes and ${VARIANTS.length} variants.`);
}

if (require.main === module) main();
module.exports = { sizesFor };
